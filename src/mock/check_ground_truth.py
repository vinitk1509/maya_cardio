"""Ground truth validation tool comparing exported device or cloud JSONL files against expected synthetic signal values.

Verifies:
  1. No duplicate samples exist.
  2. Every exported sample matches the exact values generated by the mock for that seed and mode.
  3. Every missing index is accounted for in an explicit loss record with a reason (no silent loss).
  4. Loss records do not contain fabricated or invalid ranges.
"""
import argparse
import json
import sys
from typing import Any, Dict, List, Optional, Set, Tuple

from src.mock.biosignal_mock import SignalGenerator, RATE


class GroundTruthChecker:

    def __init__(self, mode: str, seed: int):
        self.mode = mode
        self.seed = seed
        self.generator = SignalGenerator(mode, seed)

    def verify_export_file(
        self,
        export_filepath: str,
        expected_max_samples: Optional[int] = None
    ) -> Dict[str, Any]:
        """Parse export file and compare against ground truth."""
        samples_by_sensor: Dict[int, Dict[int, List[int]]] = {1: {}, 2: {}}
        losses_by_sensor: Dict[int, List[Dict[str, Any]]] = {1: [], 2: []}

        duplicate_count = 0
        value_mismatch_count = 0
        mismatch_details = []

        total_lines = 0

        with open(export_filepath, "r", encoding="utf-8") as f:
            for line_no, line in enumerate(f, start=1):
                line = line.strip()
                if not line:
                    continue
                total_lines += 1
                try:
                    record = json.loads(line)
                except Exception as e:
                    return {
                        "passed": False,
                        "error": f"Line {line_no} invalid JSON: {e}"
                    }

                sensor = record.get("sensor")
                if sensor not in (1, 2):
                    return {
                        "passed": False,
                        "error": f"Line {line_no} invalid sensor {sensor}"
                    }

                if "index" in record:
                    # Sample record: {"sensor": 1, "index": 120000, "values": [720, 1200, 1560]}
                    idx = record["index"]
                    vals = record["values"]

                    if idx in samples_by_sensor[sensor]:
                        duplicate_count += 1
                    else:
                        samples_by_sensor[sensor][idx] = vals

                    # Verify against ground truth
                    expected_vals = self.generator.get_sample(sensor, idx)
                    if vals != expected_vals:
                        value_mismatch_count += 1
                        if len(mismatch_details) < 5:
                            mismatch_details.append({
                                "sensor": sensor,
                                "index": idx,
                                "expected": expected_vals,
                                "actual": vals
                            })

                elif "from_index" in record:
                    # Loss record: {"sensor": 2, "from_index": 4000, "to_index": 4399, "reason": "..."}
                    losses_by_sensor[sensor].append(record)
                else:
                    return {
                        "passed": False,
                        "error": f"Line {line_no} unrecognized record format: {line}"
                    }

        # Analyze continuity and check for silent losses
        silent_loss_count = 0
        silent_loss_examples = []

        for sensor in (1, 2):
            stored_indices = samples_by_sensor[sensor]
            if not stored_indices and not losses_by_sensor[sensor]:
                continue

            max_stored = max(stored_indices.keys()) if stored_indices else -1
            max_check = expected_max_samples if expected_max_samples is not None else max_stored + 1

            # Build set of covered loss indices
            loss_covered_indices: Set[int] = set()
            for loss in losses_by_sensor[sensor]:
                f_idx = loss["from_index"]
                t_idx = loss["to_index"]
                if t_idx is None:
                    # Open-ended loss (e.g. session restart with unknown end)
                    # Covers everything from f_idx up to max_check
                    for k in range(f_idx, max_check):
                        loss_covered_indices.add(k)
                else:
                    for k in range(f_idx, t_idx + 1):
                        loss_covered_indices.add(k)

            # Check every index from 0 to max_check
            for k in range(0, max_check):
                if k not in stored_indices and k not in loss_covered_indices:
                    silent_loss_count += 1
                    if len(silent_loss_examples) < 5:
                        silent_loss_examples.append({"sensor": sensor, "index": k})

        passed = (duplicate_count == 0 and value_mismatch_count == 0 and silent_loss_count == 0)

        return {
            "passed": passed,
            "total_lines": total_lines,
            "sensor_1_samples": len(samples_by_sensor[1]),
            "sensor_2_samples": len(samples_by_sensor[2]),
            "sensor_1_losses": len(losses_by_sensor[1]),
            "sensor_2_losses": len(losses_by_sensor[2]),
            "duplicates": duplicate_count,
            "value_mismatches": value_mismatch_count,
            "silent_losses": silent_loss_count,
            "mismatch_details": mismatch_details,
            "silent_loss_examples": silent_loss_examples
        }


def main():
    parser = argparse.ArgumentParser(description="MayaCardio Ground Truth Verification Tool")
    parser.add_argument("export_file", help="Path to exported JSONL file")
    parser.add_argument("--mode", choices=["signal", "ramp"], default="signal", help="Mock signal mode")
    parser.add_argument("--seed", type=int, default=7, help="RNG seed")
    parser.add_argument("--expected-samples", type=int, default=None, help="Total expected samples to verify")

    args = parser.parse_args()
    checker = GroundTruthChecker(mode=args.mode, seed=args.seed)
    res = checker.verify_export_file(args.export_file, expected_max_samples=args.expected_samples)

    print(json.dumps(res, indent=2))
    if not res["passed"]:
        sys.exit(1)


if __name__ == "__main__":
    main()
